    /** 全部病种名称（扁平，供 datalist 建议） */
    public static function all(): array
    {
        $names = [];
        foreach (self::groups() as $subGroups) {
            foreach ($subGroups as $items) {
                foreach ($items as $name) {
                    $names[] = $name;
                }
            }
        }
        return $names;
    }

    public static function count(): int
    {
        return count(self::all());
    }
